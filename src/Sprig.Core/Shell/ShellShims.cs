using System.Text;

namespace Sprig.Core.Shell;

/// <summary>
/// Small <c>sprig</c> commands for PATH that let <c>sprig cd</c> move the shell you typed it in. A program
/// can't change its parent's directory, but PowerShell runs a <c>.ps1</c> found on PATH inside the calling
/// session and cmd runs a <c>.cmd</c> inside the calling window. So each shim creates an empty directives
/// file, names it in <see cref="DirectivesVariable"/>, runs the real <c>sprig.exe</c>, then applies the
/// <c>cd</c> line sprig wrote there. Git Bash runs its shim as a separate process, so there it just hands over
/// to the exe and <c>sprig cd</c> keeps opening a window.
/// <para>
/// The shims must sit in a folder of their own: cmd picks <c>sprig.exe</c> over <c>sprig.cmd</c> in the
/// same folder, which would bypass the shim.
/// </para>
/// </summary>
public static class ShellShims
{
    /// <summary>Set by a shim to the file it will read after sprig exits; absent when nothing can apply a
    /// directive, in which case <c>sprig cd</c> opens a window.</summary>
    public const string DirectivesVariable = "SPRIG_SHELL_DIRECTIVES";

    const string Marker = "Generated by sprig; do not edit.";

    /// <summary>Ask the calling shim to move its shell to <paramref name="directory"/>. False when sprig wasn't
    /// run through a shim that can, so the caller should fall back to another way of getting there.</summary>
    public static bool TryRequestCd(string directory)
    {
        if (Environment.GetEnvironmentVariable(DirectivesVariable) is not { Length: > 0 } file || !File.Exists(file))
            return false;
        File.AppendAllText(file, $"cd {Path.GetFullPath(directory)}\n");
        return true;
    }

    /// <summary>Write the shims for <paramref name="exePath"/> into <paramref name="directory"/>, returning their
    /// paths. Safe to repeat on every install or update. With <paramref name="powerShell"/> false,
    /// <c>sprig.ps1</c> is left out (and removed if present): where scripts are blocked PowerShell fails on it
    /// outright rather than falling back to <c>sprig.cmd</c>.</summary>
    public static IReadOnlyList<string> Write(string directory, string exePath, bool powerShell = true)
    {
        Directory.CreateDirectory(directory);
        var files = new List<(string Name, string Content, Encoding Encoding)>();
        // A BOM so Windows PowerShell 5.1 reads a non-ASCII path in the script as UTF-8, not the ANSI codepage.
        if (powerShell) files.Add(("sprig.ps1", PowerShell(exePath), new UTF8Encoding(encoderShouldEmitUTF8Identifier: true)));
        else File.Delete(Path.Combine(directory, "sprig.ps1"));
        files.Add(("sprig.cmd", Cmd(exePath), new UTF8Encoding(false)));
        files.Add(("sprig", Bash(exePath), new UTF8Encoding(false)));

        var written = new List<string>();
        foreach (var (name, content, encoding) in files)
        {
            var path = Path.Combine(directory, name);
            // cmd reads a batch file as it runs it, so rewriting sprig.cmd under a `sprig update` that is
            // running through it could garble the rest of that run. Unchanged files are left alone.
            var bytes = encoding.GetPreamble().Concat(encoding.GetBytes(content)).ToArray();
            if (!File.Exists(path) || !File.ReadAllBytes(path).AsSpan().SequenceEqual(bytes))
                File.WriteAllBytes(path, bytes);
            written.Add(path);
        }
        return written;
    }

    public static string PowerShell(string exePath) => $$"""
        # {{Marker}} PowerShell runs a script found on PATH inside the calling session,
        # which is what lets `sprig cd` move it. Only a cd to an existing absolute folder is applied.
        $directives = Join-Path ([IO.Path]::GetTempPath()) ("sprig-shell-" + [guid]::NewGuid().ToString('N') + '.txt')
        [IO.File]::WriteAllText($directives, '')
        $previous = $env:{{DirectivesVariable}}
        $env:{{DirectivesVariable}} = $directives
        try {
            & '{{exePath.Replace("'", "''")}}' @args
            $code = $LASTEXITCODE
        }
        finally {
            $env:{{DirectivesVariable}} = $previous
        }
        foreach ($line in [IO.File]::ReadAllLines($directives)) {
            if ($line.StartsWith('cd ')) {
                $target = $line.Substring(3)
                # Checked first because Windows PowerShell's IsPathRooted throws on a character a path can't hold.
                if ($target.IndexOfAny([IO.Path]::GetInvalidPathChars()) -ge 0) { continue }
                if ([IO.Path]::IsPathRooted($target) -and (Test-Path -LiteralPath $target -PathType Container)) { Set-Location -LiteralPath $target }
            }
        }
        Remove-Item -LiteralPath $directives -ErrorAction SilentlyContinue
        exit $code

        """.ReplaceLineEndings("\r\n");

    // Everything is decided under setlocal. The target crosses endlocal and reaches `cd` only inside quotes, and
    // a Windows path can't contain a quote (one that does is refused), so &, |, ^ and % in it stay literal.
    // No ( ) blocks anywhere: a ")" in a path such as "Program Files (x86)" would end one.
    public static string Cmd(string exePath) => $$"""
        @echo off
        rem {{Marker}} cmd runs a batch file inside the calling window, which is what lets
        rem `sprig cd` move it. Only a cd to an existing absolute folder is applied.
        setlocal EnableExtensions DisableDelayedExpansion
        set "{{DirectivesVariable}}="
        call :lasting || goto run
        set "{{DirectivesVariable}}=%TEMP%\sprig-shell-%RANDOM%%RANDOM%%RANDOM%.txt"
        type nul > "%{{DirectivesVariable}}%"
        :run
        "{{CmdPath(exePath)}}" %*
        set "sprig_code=%ERRORLEVEL%"
        set "sprig_target="
        if not defined {{DirectivesVariable}} goto done
        for /f "usebackq tokens=1,* delims= " %%a in ("%{{DirectivesVariable}}%") do if "%%a"=="cd" set "sprig_target=%%b"
        del "%{{DirectivesVariable}}%" 2>nul
        call :valid || set "sprig_target="
        :done
        endlocal & set "sprig_target=%sprig_target%" & set "sprig_code=%sprig_code%"
        if defined sprig_target cd /d "%sprig_target%"
        set "sprig_target=" & set "sprig_code=" & exit /b %sprig_code%

        rem Succeeds when this cmd will outlive the command. One started with /c (as PowerShell does to run a .cmd)
        rem exits straight after, so moving it would do nothing; sprig opens a window instead.
        rem A quote inside an IF upsets its parsing even under delayed expansion, so compare quote-free copies.
        :lasting
        setlocal EnableDelayedExpansion
        set "line=!CMDCMDLINE:"=!"
        set "rest=!line: /c=!"
        if not "!rest!"=="!line!" exit /b 1
        exit /b 0

        rem Succeeds when sprig_target is a quote-free absolute path to an existing folder.
        :valid
        if not defined sprig_target exit /b 1
        setlocal EnableDelayedExpansion
        set "t=!sprig_target:"=!"
        if not "!t!"=="!sprig_target!" exit /b 1
        if not "!t:~1,2!"==":\" if not "!t:~0,2!"=="\\" exit /b 1
        if not exist "!t!\" exit /b 1
        exit /b 0

        """.ReplaceLineEndings("\r\n");

    public static string Bash(string exePath) => $$"""
        #!/usr/bin/env bash
        # {{Marker}} Git Bash runs this as a separate process, so `sprig cd` can't move
        # your shell from here and opens a window instead. To move this shell:  cd "$(sprig path <workspace>)"
        exec '{{PosixPath(exePath).Replace("'", "'\\''")}}' "$@"

        """.ReplaceLineEndings("\n");

    /// <summary>The exe path as it is written into the cmd shim. cmd reads a batch file in the console's code
    /// page, so a non-ASCII folder (usually the user's own name) is written as <c>%LOCALAPPDATA%</c> or
    /// <c>%USERPROFILE%</c> where it falls under one; a literal <c>%</c> is doubled so cmd keeps it.</summary>
    internal static string CmdPath(string exePath)
    {
        foreach (var variable in new[] { "LOCALAPPDATA", "USERPROFILE" })
        {
            var root = Environment.GetEnvironmentVariable(variable);
            if (string.IsNullOrEmpty(root)) continue;
            var prefix = Path.TrimEndingDirectorySeparator(root) + Path.DirectorySeparatorChar;
            if (exePath.StartsWith(prefix, StringComparison.OrdinalIgnoreCase))
                return $"%{variable}%\\" + exePath[prefix.Length..].Replace("%", "%%");
        }
        return exePath.Replace("%", "%%");
    }

    /// <summary><c>C:\x\y</c> as Git Bash writes it, <c>/c/x/y</c>.</summary>
    internal static string PosixPath(string windowsPath)
    {
        var p = windowsPath.Replace('\\', '/');
        return p.Length >= 2 && p[1] == ':' ? $"/{char.ToLowerInvariant(p[0])}{p[2..]}" : p;
    }
}
